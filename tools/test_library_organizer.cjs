const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const source=fs.readFileSync('64x64_matrix_01.ino','utf8');
const script=source.split('// LIBRARY_ORGANIZER_START')[1].split('// LIBRARY_ORGANIZER_MODEL_END')[0].split('\n').slice(1).join('\n');
const ctx=vm.createContext({state:{bookmarks:[false,false,true]},Map,Set});
vm.runInContext(script,ctx);
vm.runInContext(`libraryData={folders:['Acid'],families:['Custom family'],tags:['acid','geometric'],entries:[[1,5,1,0,3],[63,4,0,0,1],[70,2,0,1,0]]};`,ctx);
const items=[{key:'n1',engine:1,variant:null,name:'Warped Checkerboard',source:'Native',previewIndex:0},{key:'p47',engine:16,variant:47,name:'Interference',source:'Native',previewIndex:1},{key:'p54',engine:16,variant:54,name:'Orbits',source:'Native',previewIndex:2}];
const opts={query:'',folder:'',tag:'',rating:0,sort:'rating',group:false,starred:false};
const select=o=>ctx.librarySelection(items,{...opts,...o}).map(x=>x.key);
assert.equal(ctx.metadataId(items[1]),63);
assert.equal(ctx.metadataFor(items[0]).rating,5);
assert.deepEqual([...select({})],['p54','n1','p47'],'bookmarks first');
assert.deepEqual([...select({tag:'acid',rating:5})],['n1']);
assert.deepEqual([...select({folder:'__unfiled__'})],['p54','p47']);
assert.deepEqual([...select({query:'geometric'})],['n1']);
assert.deepEqual([...select({group:true})],['p54','n1','p47']);
assert.equal(ctx.familyFor(items[1]),'Warped Checkerboard');
assert.equal(ctx.familyFor(items[2]),'Custom family');
assert.equal(ctx.defaultFamily({key:'p59',name:'v2'}),'Whitney — Resonant Orbits');
assert.equal(select({rating:-1}).length,0);
vm.runInContext('libraryData.entries[1].push(true)',ctx);
assert.deepEqual([...select({})],['p54','n1']);
assert.deepEqual([...select({view:'archived'})],['p47']);
assert.deepEqual([...select({view:'archived',rating:5})],[]);
assert.equal(ctx.defaultFamily({key:'p62',name:'Liquid Circuit'}),'Warped Checkerboard');
assert.equal(ctx.metadataFor(items[1]).rating,4,'archival preserves rating');
vm.runInContext('libraryData.entries[1][5]=false',ctx);
assert.equal(select({}).length,3,'restore');
console.log('PASS ratings, stable IDs, bookmarks, combined filters, folder/tag search, variant grouping');
